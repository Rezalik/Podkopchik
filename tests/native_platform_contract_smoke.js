'use strict';
const fs=require('fs');
const assert=require('assert');
const lib='root/usr/libexec/podkopchik/';
const model=fs.readFileSync(lib+'native_platform.uc','utf8');
const collector=fs.readFileSync(lib+'native_platform_check.uc','utf8')+fs.readFileSync(lib+'native_platform_probe.uc','utf8');
const fixture=JSON.parse(fs.readFileSync('tests/fixtures/native-platform-flint2.json','utf8'));
assert.equal(fixture.os.board,'glinet,gl-mt6000');
assert(model.includes('installation_authorized:false,activation_authorized:false'));
assert(model.includes("physical_acceptance:'not_assessed'"));
assert(collector.includes(" -run-timeout 4 -- sh -c "));
assert(collector.includes('caps.bounded_commands!==true') && collector.includes('stat.uid==0'));
assert(collector.includes('p.read(65537)') && collector.includes('length(out)<=65536'));
assert(!/fs\.(writefile|open|mkdir|unlink|rename|chmod)|\.set\(|\.commit\(|\.save\(|\bsystem\(/.test(collector));
assert(!/native-emergency|native-confirm|update-install|\breboot\b|\bmodprobe\b|\bopkg\b|\bapk\b/.test(collector));
assert(!/\/etc\/config\/podkopchik|\/etc\/podkopchik\/awg|\.uri\b|private_key|logread/.test(collector));
assert(collector.includes("c.load('firewall')"));
const component=fs.readFileSync('native/runtime/install-dns-component.sh','utf8');
const installer=fs.readFileSync('tools/install-native-rc-files.sh','utf8');
const updater=fs.readFileSync(lib+'native_update.sh','utf8');
assert(component.includes('admission=admit') && component.includes('native_package_check.uc'));
assert(installer.indexOf(' --preflight') < installer.indexOf('committing=1'));
assert(updater.includes('native_package_check.uc" admit') && !updater.includes('. /etc/openwrt_release'));
assert(!fs.readFileSync('root/usr/bin/podkopchikctl','utf8').includes('native_platform_check.uc'),'stage 1 must not alter runtime dispatch');
console.log('PASS: platform contract, bounded read-only collector, privacy and shared package admission wiring');
